  exit;
}

add_action('init', function () {
	register_taxonomy('door_family', ['product'], [
		'labels' => [
			'name'                       => 'Сем-во',
			'singular_name'              => 'Семейство двери',
			'menu_name'                  => 'Семейства дверей',
			'all_items'                  => 'Все семейства',
			'edit_item'                  => 'Редактировать семейство',
			'view_item'                  => 'Просмотреть семейство',
			'update_item'                => 'Обновить семейство',
			'add_new_item'               => 'Добавить семейство',
			'new_item_name'              => 'Название семейства',
			'search_items'               => 'Искать семейство',
			'popular_items'              => 'Популярные семейства',
			'separate_items_with_commas' => 'Разделяйте семейства запятыми',
			'add_or_remove_items'        => 'Добавить или удалить семейства',
			'choose_from_most_used'      => 'Выбрать из часто используемых',
			'not_found'                  => 'Семейства не найдены',
		],
    'public' => false,
    // НЕ ОБЯЗАТЕЛЬНО.
    // Делает таксономию публичной или служебной.
    // false = не публичная бизнес-сущность для фронта WordPress.
    // Для твоего проекта это правильно:
    // family нужен как внутренняя группировка товаров, а не как публичный архив.

    'publicly_queryable' => false,
    // НЕ ОБЯЗАТЕЛЬНО.
    // Разрешать ли публичные query по таксономии с фронта WP.
    // false = не хотим отдельные публичные URL / запросы по family в самом WordPress.

    'show_ui' => true,
    // НЕ ОБЯЗАТЕЛЬНО, но практически нужно.
    // Показывать ли UI управления таксономией в админке.
    // true = можно создавать/редактировать семейства через админку.

    'show_admin_column' => true,
    // НЕ ОБЯЗАТЕЛЬНО.
    // Добавить колонку таксономии в список товаров в админке.
    // Удобно, чтобы сразу видеть family у товара.

    'show_in_nav_menus' => false,
    // НЕ ОБЯЗАТЕЛЬНО.
    // Можно ли использовать термины этой таксономии в меню WordPress.
    // Для family не нужно, поэтому false.

    'show_tagcloud' => false,
    // НЕ ОБЯЗАТЕЛЬНО.
    // Показывать ли облако терминов.
    // Для family не нужно.

    'show_in_rest' => true,
    // НЕ ОБЯЗАТЕЛЬНО технически, но ОБЯЗАТЕЛЬНО для твоего headless-сценария.
    // Делает таксономию доступной через REST API.
    // Без этого BFF / Next не смогут нормально читать taxonomy через WP REST.

    'hierarchical' => false,
    // НЕ ОБЯЗАТЕЛЬНО.
    // false = поведение как у тегов (плоский список).
    // true  = поведение как у категорий (дерево).
    // Для door_family правильно false,
    // потому что семейства не образуют иерархию.

    'rewrite' => false,
    // НЕ ОБЯЗАТЕЛЬНО.
    // Настраивает URL rewrite для публичных страниц таксономии.
    // false = не создаём URL-слой вида /door_family/dk01/.
    // Для твоего случая это правильно, потому что family не должен лезть в SEO URL.

    'query_var' => true,
    // НЕ ОБЯЗАТЕЛЬНО.
    // Разрешает использовать query var для таксономии.
    // Обычно можно оставить true.
    // Не критичный аргумент в твоём сценарии.

    'sort' => false,
    // НЕ ОБЯЗАТЕЛЬНО.
    // Управляет сортировкой терминов в интерфейсе назначения.
    // Обычно не нужен, false нормально.

    // Ниже можно было бы добавить и другие аргументы,
    // но для твоего кейса они не обязательны.
	]);
});